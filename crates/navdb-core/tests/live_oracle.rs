//! Live Oracle driver test. Run against a real server with
//! `NAVDB_LIVE=1 cargo test -p navdb-core --test live_oracle -- --test-threads=1`.
//!
//! Defaults match `gvenzl/oracle-free:23-slim-faststart` on 127.0.0.1:11521
//! (APP_USER navdb/navdb, service FREEPDB1). Oracle Instant Client must be
//! installed; point `NAVDB_ORACLE_CLIENT_DIR` at it when it is not on the
//! default search path.

use navdb_core::driver::{self, Driver};
use navdb_core::*;

fn live() -> bool {
    std::env::var("NAVDB_LIVE").is_ok()
}

fn env(k: &str, d: &str) -> String {
    std::env::var(k).unwrap_or_else(|_| d.to_string())
}

fn cfg() -> ConnectionConfig {
    let mut c = ConnectionConfig {
        host: env("NAVDB_ORACLE_HOST", "127.0.0.1"),
        port: env("NAVDB_ORACLE_PORT", "11521").parse().unwrap_or(11521),
        user: env("NAVDB_ORACLE_USER", "navdb"),
        password: env("NAVDB_ORACLE_PASSWORD", "navdb"),
        database: env("NAVDB_ORACLE_SERVICE", "FREEPDB1"),
        ..ConnectionConfig::new(DbKind::Oracle)
    };
    if let Ok(dir) = std::env::var("NAVDB_ORACLE_CLIENT_DIR") {
        c.options.insert("oracle_client_dir".into(), dir);
    }
    c
}

#[test]
fn missing_client_gives_friendly_error() {
    if live() || oracle::InitParams::is_initialized() {
        return;
    }
    let mut c = cfg();
    c.options.insert("oracle_client_dir".into(), "/nonexistent/instantclient".into());
    let err = match driver::connect(&c) {
        Ok(_) => panic!("connected without an Oracle client"),
        Err(e) => format!("{:#}", e),
    };
    assert!(err.contains("Oracle Instant Client not found"), "{}", err);
    assert!(err.contains("instant-client/downloads.html"), "{}", err);
    assert!(err.contains("DPI-1047"), "underlying message missing: {}", err);
}

fn drop_all(d: &mut dyn Driver, scope: &Scope) {
    for (kind, name) in [
        ("VIEW", "NAVDB_V"),
        ("TABLE", "NAVDB_CHILD"),
        ("TABLE", "NAVDB_ITEMS"),
        ("FUNCTION", "NAVDB_ADD1"),
        ("SEQUENCE", "NAVDB_SEQ"),
    ] {
        let extra = if kind == "TABLE" { " PURGE" } else { "" };
        d.execute(
            Some(scope),
            &format!("BEGIN EXECUTE IMMEDIATE 'DROP {} {}{}'; EXCEPTION WHEN OTHERS THEN NULL; END;\n/", kind, name, extra),
        )
        .unwrap();
    }
}

#[test]
fn oracle_roundtrip() {
    if !live() {
        return;
    }
    let c = cfg();
    let mut d = driver::connect(&c).unwrap_or_else(|e| panic!("connect: {:#}", e));
    let ver = d.server_version().unwrap();
    assert!(ver.contains("Oracle"), "{}", ver);
    println!("server: {}", ver);
    d.ping().unwrap();
    assert!(!d.kind().has_schemas());

    let dbs = d.list_databases().unwrap();
    assert!(dbs.contains(&"NAVDB".to_string()), "{:?}", dbs);
    assert!(!dbs.contains(&"SYS".to_string()), "{:?}", dbs);
    let scope = Scope::new("NAVDB", None);
    let dialect = d.dialect();
    drop_all(d.as_mut(), &scope);

    // multi-statement script with PL/SQL
    let script = "CREATE TABLE NAVDB_ITEMS (\n  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  NAME VARCHAR2(50) DEFAULT 'x' NOT NULL,\n  \
        PRICE NUMBER(10,2),\n  CREATED DATE,\n  DATA RAW(16),\n  RATIO BINARY_DOUBLE,\n  NOTE CLOB,\n  QTY NUMBER(5) CHECK (QTY >= 0)\n);\n\
        CREATE INDEX IX_NAVDB_ITEMS_NAME ON NAVDB_ITEMS (NAME);\n\
        COMMENT ON COLUMN NAVDB_ITEMS.NAME IS 'the name';\n\
        COMMENT ON TABLE NAVDB_ITEMS IS 'items table';\n\
        CREATE TABLE NAVDB_CHILD (ID NUMBER(10) PRIMARY KEY, ITEM_ID NUMBER, CONSTRAINT FK_CHILD_ITEM FOREIGN KEY (ITEM_ID) REFERENCES NAVDB_ITEMS (ID) ON DELETE CASCADE);\n\
        CREATE OR REPLACE FUNCTION NAVDB_ADD1(x NUMBER) RETURN NUMBER IS\nBEGIN\n  RETURN x + 1;\nEND;\n/\n\
        CREATE SEQUENCE NAVDB_SEQ START WITH 5;\n\
        CREATE OR REPLACE VIEW NAVDB_V AS SELECT ID, NAME FROM NAVDB_ITEMS;\n\
        SELECT NAVDB_ADD1(41) AS V FROM DUAL;";
    let res = d.execute(Some(&scope), script).unwrap_or_else(|e| panic!("script: {:#}", e));
    assert_eq!(res.len(), 9);
    let last = res.last().unwrap();
    assert!(last.is_query);
    assert_eq!(last.rows[0][0], Value::Int(42));

    // table_def
    let p = scope.path("NAVDB_ITEMS");
    let def = d.table_def(&p).unwrap();
    let names: Vec<&str> = def.columns.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(names, vec!["ID", "NAME", "PRICE", "CREATED", "DATA", "RATIO", "NOTE", "QTY"]);
    assert!(def.columns[0].auto_increment && def.columns[0].primary_key, "{:?}", def.columns[0]);
    assert_eq!(def.columns[1].data_type, "VARCHAR2(50)");
    assert!(!def.columns[1].nullable);
    assert_eq!(def.columns[1].default.as_deref(), Some("'x'"));
    assert_eq!(def.columns[1].comment, "the name");
    assert_eq!(def.columns[2].data_type, "NUMBER(10,2)");
    assert_eq!(def.columns[4].data_type, "RAW(16)");
    assert_eq!(def.comment, "items table");
    assert_eq!(def.primary_key(), vec!["ID".to_string()]);
    assert!(def.indexes.iter().any(|i| i.name == "IX_NAVDB_ITEMS_NAME" && i.columns == vec!["NAME".to_string()]), "{:?}", def.indexes);
    assert_eq!(def.checks.len(), 1, "{:?}", def.checks);
    let cdef = d.table_def(&scope.path("NAVDB_CHILD")).unwrap();
    assert_eq!(cdef.foreign_keys.len(), 1, "{:?}", cdef.foreign_keys);
    assert_eq!(cdef.foreign_keys[0].ref_table, "NAVDB_ITEMS");
    assert_eq!(cdef.foreign_keys[0].ref_columns, vec!["ID".to_string()]);
    assert_eq!(cdef.foreign_keys[0].on_delete, "CASCADE");

    // navigator listing
    let has = |d: &mut dyn Driver, k: ObjectKind, n: &str| d.list_objects(&scope, k).unwrap().iter().any(|o| o.name == n);
    assert!(has(d.as_mut(), ObjectKind::Table, "NAVDB_ITEMS"));
    assert!(has(d.as_mut(), ObjectKind::Table, "NAVDB_CHILD"));
    assert!(has(d.as_mut(), ObjectKind::View, "NAVDB_V"));
    assert!(has(d.as_mut(), ObjectKind::Function, "NAVDB_ADD1"));
    assert!(has(d.as_mut(), ObjectKind::Sequence, "NAVDB_SEQ"));
    assert!(has(d.as_mut(), ObjectKind::Index, "IX_NAVDB_ITEMS_NAME"));
    let tables = d.list_objects(&scope, ObjectKind::Table).unwrap();
    let t = tables.iter().find(|t| t.name == "NAVDB_ITEMS").unwrap();
    assert!(!t.created.is_empty(), "{:?}", t);
    assert_eq!(t.comment, "items table");

    // grid DML
    let cols: Vec<String> = ["NAME", "PRICE", "CREATED", "DATA", "RATIO", "NOTE", "QTY"].iter().map(|s| s.to_string()).collect();
    d.execute(
        Some(&scope),
        &dml::insert_rows(dialect, &p, &cols, &[
            vec![
                Value::Text("a'b".into()),
                Value::Text("1.50".into()),
                Value::Text("2024-01-02 03:04:05".into()),
                Value::Bytes(vec![0xde, 0xad, 0xbe, 0xef]),
                Value::Float(0.25),
                Value::Text("long text".into()),
                Value::Int(3),
            ],
            vec![Value::Text("bc".into()), Value::Null, Value::Null, Value::Null, Value::Null, Value::Null, Value::Int(0)],
        ]),
    )
    .unwrap_or_else(|e| panic!("insert_rows: {:#}", e));
    let r = d
        .execute(Some(&scope), &dml::insert_row(dialect, &p, &["NAME".into(), "QTY".into()], &[Value::Text("zzb".into()), Value::Int(7)]))
        .unwrap();
    assert_eq!(r[0].affected_rows, 1);
    assert_eq!(d.count(&p).unwrap(), 3);

    let all = d.query(Some(&scope), &dml::select_page(dialect, &p, "", &[dml::SortSpec { column: "ID".into(), descending: false }], 1000, 0)).unwrap();
    assert_eq!(all.rows.len(), 3);
    let row = &all.rows[0];
    assert!(matches!(row[0], Value::Int(_)), "{:?}", row);
    assert_eq!(row[1], Value::Text("a'b".into()));
    assert_eq!(row[2], Value::Text("1.5".into()));
    assert_eq!(row[3], Value::Text("2024-01-02 03:04:05".into()));
    assert_eq!(row[4], Value::Bytes(vec![0xde, 0xad, 0xbe, 0xef]));
    assert_eq!(row[5], Value::Float(0.25));
    assert_eq!(row[6], Value::Text("long text".into()));
    assert_eq!(row[7], Value::Int(3));
    assert_eq!(all.columns[1].type_name, "VARCHAR2(50)");
    let first_id = row[0].clone();

    let mut f = dml::FilterRule::new("NAME");
    f.op = dml::FilterOp::Contains;
    f.value = "b".into();
    let w = dml::filters_to_where(dialect, &[f]);
    let sort = [dml::SortSpec { column: "ID".into(), descending: false }];
    let page = d.query(Some(&scope), &dml::select_page(dialect, &p, &w, &sort, 2, 1)).unwrap();
    assert_eq!(page.rows.len(), 2, "{:?}", page.rows);
    assert_eq!(page.rows[0][1], Value::Text("bc".into()));
    assert_eq!(page.rows[1][1], Value::Text("zzb".into()));
    let cnt = d.query(Some(&scope), &dml::count_rows(dialect, &p, &w)).unwrap();
    assert_eq!(cnt.rows[0][0], Value::Int(3));

    let key = [("ID".to_string(), first_id.clone())];
    d.execute(
        Some(&scope),
        &dml::update_row(dialect, &p, &[("PRICE".into(), Value::Text("9.99".into())), ("CREATED".into(), Value::Text("2025-05-06 07:08:09".into()))], &key),
    )
    .unwrap();
    let back = d.query(Some(&scope), &format!("SELECT PRICE, CREATED FROM NAVDB_ITEMS WHERE ID = {}", first_id)).unwrap();
    assert_eq!(back.rows[0], vec![Value::Text("9.99".into()), Value::Text("2025-05-06 07:08:09".into())]);
    // keyless update with all original values (incl. NULLs)
    let orig = d.query(Some(&scope), "SELECT NAME, QTY, PRICE FROM NAVDB_ITEMS WHERE NAME = 'bc'").unwrap();
    let keys: Vec<(String, Value)> = orig.columns.iter().zip(orig.rows[0].iter()).map(|(c, v)| (c.name.clone(), v.clone())).collect();
    let r = d.execute(Some(&scope), &dml::update_row(dialect, &p, &[("QTY".into(), Value::Int(11))], &keys)).unwrap();
    assert_eq!(r[0].affected_rows, 1);

    let r = d.execute(Some(&scope), &dml::delete_row(dialect, &p, &key)).unwrap();
    assert_eq!(r[0].affected_rows, 1);
    assert_eq!(d.count(&p).unwrap(), 2);

    // DDL
    let ddl = d.object_ddl(&p, ObjectKind::Table).unwrap();
    assert!(ddl.contains("CREATE TABLE") && ddl.contains("NAVDB_ITEMS"), "{}", ddl);
    let fddl = d.object_ddl(&scope.path("NAVDB_ADD1"), ObjectKind::Function).unwrap();
    assert!(fddl.contains("RETURN x + 1"), "{}", fddl);
    let vddl = d.object_ddl(&scope.path("NAVDB_V"), ObjectKind::View).unwrap();
    assert!(vddl.to_uppercase().contains("VIEW"), "{}", vddl);
    let sddl = d.object_ddl(&scope.path("NAVDB_SEQ"), ObjectKind::Sequence).unwrap();
    assert!(sddl.contains("NAVDB_SEQ"), "{}", sddl);

    // explain
    let plan = d.explain(Some(&scope), "SELECT * FROM NAVDB_ITEMS WHERE ID = 1;").unwrap();
    assert!(!plan.rows.is_empty());
    assert!(plan.rows.iter().any(|r| r[0].to_string().contains("NAVDB_ITEMS")), "{:?}", plan.rows);

    // errors carry the server message
    let e = d.execute(Some(&scope), "SELECT * FROM NO_SUCH_TABLE_X").unwrap_err();
    assert!(format!("{:#}", e).contains("ORA-00942"), "{:#}", e);

    // monitor / users (privileges may be missing for an app user)
    let snap = d.server_snapshot().unwrap();
    assert!(!snap.processes.columns.is_empty());
    let users = d.list_users().unwrap();
    assert!(users.iter().any(|u| u.name == "NAVDB"));

    // scope switch: query NAVDB objects while the session sits in another schema
    let other = Scope::new("SYSTEM", None);
    let _ = d.execute(Some(&other), "SELECT 1 FROM DUAL");
    assert_eq!(d.count(&p).unwrap(), 2);

    drop_all(d.as_mut(), &scope);
    assert!(!d.list_objects(&scope, ObjectKind::Table).unwrap().iter().any(|t| t.name == "NAVDB_ITEMS"));
}
