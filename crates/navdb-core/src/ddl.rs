//! DDL generation for the designers and synchronization tools.

use crate::dialect::Dialect;
use crate::model::*;

fn col_list(d: Dialect, cols: &[String]) -> String {
    cols.iter().map(|c| d.quote_ident(c)).collect::<Vec<_>>().join(", ")
}

/// Column definition fragment (without trailing comma).
pub fn column_sql(d: Dialect, c: &ColumnDef, inline_pk: bool) -> String {
    let mut s = format!("{} ", d.quote_ident(&c.name));
    let mut ty = c.data_type.trim().to_string();
    if ty.is_empty() {
        ty = match d {
            Dialect::Sqlite => "TEXT".into(),
            _ => "varchar(255)".into(),
        };
    }
    if d == Dialect::Postgres && c.auto_increment {
        let lower = ty.to_ascii_lowercase();
        if !lower.contains("serial") {
            s.push_str(&ty);
            s.push_str(" GENERATED BY DEFAULT AS IDENTITY");
        } else {
            s.push_str(&ty);
        }
    } else {
        s.push_str(&ty);
    }
    if d == Dialect::MySql && !c.collation.is_empty() {
        s.push_str(&format!(" COLLATE {}", c.collation));
    }
    if !c.nullable {
        s.push_str(" NOT NULL");
    } else if d == Dialect::MySql && ty.to_ascii_lowercase().starts_with("timestamp") {
        s.push_str(" NULL");
    }
    if let Some(def) = &c.default {
        if !def.is_empty() {
            s.push_str(&format!(" DEFAULT {}", def));
        }
    }
    if inline_pk && c.primary_key {
        s.push_str(" PRIMARY KEY");
        if d == Dialect::Sqlite && c.auto_increment {
            s.push_str(" AUTOINCREMENT");
        }
    }
    if d == Dialect::MySql {
        if c.auto_increment {
            s.push_str(" AUTO_INCREMENT");
        }
        if !c.extra.is_empty() && !c.extra.to_ascii_lowercase().contains("auto_increment") {
            let extra = c.extra.replace("DEFAULT_GENERATED", "");
            let extra = extra.trim();
            if !extra.is_empty() {
                s.push(' ');
                s.push_str(extra);
            }
        }
        if !c.comment.is_empty() {
            s.push_str(&format!(" COMMENT {}", d.string_literal(&c.comment)));
        }
    }
    s
}

fn fk_sql(d: Dialect, fk: &ForeignKeyDef) -> String {
    let ref_path = ObjPath::new(fk.ref_db.clone(), fk.ref_schema.clone(), fk.ref_table.clone());
    let target = match d {
        // within same database keep it short
        Dialect::Sqlite => d.quote_ident(&fk.ref_table),
        Dialect::MySql if fk.ref_db.is_empty() => d.quote_ident(&fk.ref_table),
        _ => d.qualify(&ref_path),
    };
    let mut s = String::new();
    if !fk.name.is_empty() {
        s.push_str(&format!("CONSTRAINT {} ", d.quote_ident(&fk.name)));
    }
    s.push_str(&format!(
        "FOREIGN KEY ({}) REFERENCES {} ({})",
        col_list(d, &fk.columns),
        target,
        col_list(d, &fk.ref_columns)
    ));
    if !fk.on_delete.is_empty() && !fk.on_delete.eq_ignore_ascii_case("NO ACTION") {
        s.push_str(&format!(" ON DELETE {}", fk.on_delete));
    }
    if !fk.on_update.is_empty() && !fk.on_update.eq_ignore_ascii_case("NO ACTION") {
        s.push_str(&format!(" ON UPDATE {}", fk.on_update));
    }
    s
}

fn index_sql(d: Dialect, table: &TableDef, idx: &IndexDef) -> String {
    let t = d.qualify(&table.path);
    match d {
        Dialect::MySql => {
            let kind = if idx.unique {
                "UNIQUE INDEX"
            } else if idx.method.eq_ignore_ascii_case("FULLTEXT") {
                "FULLTEXT INDEX"
            } else if idx.method.eq_ignore_ascii_case("SPATIAL") {
                "SPATIAL INDEX"
            } else {
                "INDEX"
            };
            let using = if idx.method.eq_ignore_ascii_case("BTREE") || idx.method.eq_ignore_ascii_case("HASH") {
                format!(" USING {}", idx.method.to_ascii_uppercase())
            } else {
                String::new()
            };
            format!("CREATE {} {} ON {} ({}){}", kind, d.quote_ident(&idx.name), t, col_list(d, &idx.columns), using)
        }
        Dialect::Postgres => {
            let using = if idx.method.is_empty() || idx.method.eq_ignore_ascii_case("btree") {
                String::new()
            } else {
                format!(" USING {}", idx.method.to_ascii_lowercase())
            };
            format!(
                "CREATE {}INDEX {} ON {}{} ({})",
                if idx.unique { "UNIQUE " } else { "" },
                d.quote_ident(&idx.name),
                t,
                using,
                // PG index columns may be expressions; quote plain names only
                idx.columns.iter().map(|c| quote_if_plain(d, c)).collect::<Vec<_>>().join(", ")
            )
        }
        Dialect::Sqlite => {
            let iname = if table.path.db.is_empty() || table.path.db == "main" {
                d.quote_ident(&idx.name)
            } else {
                format!("{}.{}", d.quote_ident(&table.path.db), d.quote_ident(&idx.name))
            };
            format!(
                "CREATE {}INDEX {} ON {} ({})",
                if idx.unique { "UNIQUE " } else { "" },
                iname,
                d.quote_ident(&table.path.name),
                col_list(d, &idx.columns)
            )
        }
        _ => format!(
            "CREATE {}INDEX {} ON {} ({})",
            if idx.unique { "UNIQUE " } else { "" },
            d.quote_ident(&idx.name),
            t,
            col_list(d, &idx.columns)
        ),
    }
}

fn quote_if_plain(d: Dialect, c: &str) -> String {
    if c.chars().all(|ch| ch.is_alphanumeric() || ch == '_') {
        d.quote_ident(c)
    } else {
        c.to_string()
    }
}

/// Full `CREATE TABLE` script (table + separate index/comment statements).
pub fn create_table(d: Dialect, t: &TableDef) -> Vec<String> {
    let mut out = Vec::new();
    let pk = t.primary_key();
    let single_inline_pk = d == Dialect::Sqlite
        && pk.len() == 1
        && t.columns.iter().any(|c| c.name == pk[0] && c.auto_increment);
    let mut parts: Vec<String> = t
        .columns
        .iter()
        .map(|c| {
            let mut c = c.clone();
            c.primary_key = single_inline_pk && pk.first() == Some(&c.name);
            format!("  {}", column_sql(d, &c, single_inline_pk))
        })
        .collect();
    if !pk.is_empty() && !single_inline_pk {
        parts.push(format!("  PRIMARY KEY ({})", col_list(d, &pk)));
    }
    let mut separate_indexes = Vec::new();
    for idx in t.indexes.iter().filter(|i| !i.primary) {
        if d == Dialect::MySql {
            let kind = if idx.unique {
                "UNIQUE KEY"
            } else if idx.method.eq_ignore_ascii_case("FULLTEXT") {
                "FULLTEXT KEY"
            } else if idx.method.eq_ignore_ascii_case("SPATIAL") {
                "SPATIAL KEY"
            } else {
                "KEY"
            };
            let using = if idx.method.eq_ignore_ascii_case("BTREE") || idx.method.eq_ignore_ascii_case("HASH") {
                format!(" USING {}", idx.method.to_ascii_uppercase())
            } else {
                String::new()
            };
            parts.push(format!("  {} {} ({}){}", kind, d.quote_ident(&idx.name), col_list(d, &idx.columns), using));
        } else {
            separate_indexes.push(index_sql(d, t, idx));
        }
    }
    for fk in &t.foreign_keys {
        parts.push(format!("  {}", fk_sql(d, fk)));
    }
    for ck in &t.checks {
        if ck.name.is_empty() {
            parts.push(format!("  CHECK ({})", ck.expression));
        } else {
            parts.push(format!("  CONSTRAINT {} CHECK ({})", d.quote_ident(&ck.name), ck.expression));
        }
    }
    let mut sql = format!("CREATE TABLE {} (\n{}\n)", d.qualify(&t.path), parts.join(",\n"));
    if d == Dialect::MySql {
        if !t.engine.is_empty() {
            sql.push_str(&format!(" ENGINE={}", t.engine));
        }
        if let Some(ai) = t.auto_increment {
            if ai > 1 {
                sql.push_str(&format!(" AUTO_INCREMENT={}", ai));
            }
        }
        if !t.charset.is_empty() {
            sql.push_str(&format!(" DEFAULT CHARSET={}", t.charset));
        }
        if !t.collation.is_empty() {
            sql.push_str(&format!(" COLLATE={}", t.collation));
        }
        if !t.comment.is_empty() {
            sql.push_str(&format!(" COMMENT={}", d.string_literal(&t.comment)));
        }
    }
    out.push(sql);
    out.extend(separate_indexes);
    if d == Dialect::Postgres {
        if !t.comment.is_empty() {
            out.push(format!("COMMENT ON TABLE {} IS {}", d.qualify(&t.path), d.string_literal(&t.comment)));
        }
        for c in &t.columns {
            if !c.comment.is_empty() {
                out.push(format!(
                    "COMMENT ON COLUMN {}.{} IS {}",
                    d.qualify(&t.path),
                    d.quote_ident(&c.name),
                    d.string_literal(&c.comment)
                ));
            }
        }
    }
    for tr in &t.triggers {
        out.push(create_trigger(d, &t.path, tr));
    }
    out
}

pub fn create_trigger(d: Dialect, table: &ObjPath, tr: &TriggerDef) -> String {
    match d {
        Dialect::Postgres => {
            // body is the name of a trigger function or a full definition
            if tr.body.trim_start().to_ascii_uppercase().starts_with("CREATE") {
                tr.body.clone()
            } else {
                format!(
                    "CREATE TRIGGER {} {} {} ON {} FOR EACH ROW EXECUTE FUNCTION {}",
                    d.quote_ident(&tr.name),
                    tr.timing,
                    tr.event,
                    d.qualify(table),
                    tr.body.trim().trim_end_matches(';')
                )
            }
        }
        _ => format!(
            "CREATE TRIGGER {} {} {} ON {} FOR EACH ROW {}",
            d.quote_ident(&tr.name),
            tr.timing,
            tr.event,
            if d == Dialect::Sqlite { d.quote_ident(&table.name) } else { d.qualify(table) },
            normalize_trigger_body(d, &tr.body)
        ),
    }
}

fn normalize_trigger_body(d: Dialect, body: &str) -> String {
    let b = body.trim();
    if d == Dialect::Sqlite && !b.to_ascii_uppercase().starts_with("BEGIN") {
        let inner = b.trim_end_matches(';');
        format!("BEGIN {}; END", inner)
    } else {
        b.to_string()
    }
}

/// Statements turning `old` into `new` (Table Designer "Save" / Structure Sync).
pub fn alter_table(d: Dialect, old: &TableDef, new: &TableDef) -> Vec<String> {
    if d == Dialect::Sqlite {
        return sqlite_rebuild(old, new);
    }
    let mut out = Vec::new();
    let t = d.qualify(&new.path);

    if old.path.name != new.path.name {
        let old_t = d.qualify(&old.path);
        match d {
            Dialect::MySql => out.push(format!("ALTER TABLE {} RENAME TO {}", old_t, t)),
            _ => out.push(format!("ALTER TABLE {} RENAME TO {}", old_t, d.quote_ident(&new.path.name))),
        }
    }

    // drop foreign keys that changed or vanished first
    for fk in &old.foreign_keys {
        if !new.foreign_keys.iter().any(|n| n == fk) {
            match d {
                Dialect::MySql => out.push(format!("ALTER TABLE {} DROP FOREIGN KEY {}", t, d.quote_ident(&fk.name))),
                _ => out.push(format!("ALTER TABLE {} DROP CONSTRAINT {}", t, d.quote_ident(&fk.name))),
            }
        }
    }
    // drop indexes that changed or vanished
    for idx in old.indexes.iter().filter(|i| !i.primary) {
        if !new.indexes.iter().any(|n| n == idx) {
            match d {
                Dialect::MySql => out.push(format!("ALTER TABLE {} DROP INDEX {}", t, d.quote_ident(&idx.name))),
                _ => {
                    let p = ObjPath::new(new.path.db.clone(), new.path.schema.clone(), idx.name.clone());
                    out.push(format!("DROP INDEX {}", d.qualify(&p)))
                }
            }
        }
    }
    let old_pk = old.primary_key();
    let new_pk = new.primary_key();
    if old_pk != new_pk && !old_pk.is_empty() {
        match d {
            Dialect::MySql => out.push(format!("ALTER TABLE {} DROP PRIMARY KEY", t)),
            _ => out.push(format!(
                "ALTER TABLE {} DROP CONSTRAINT {}",
                t,
                d.quote_ident(
                    &old.indexes
                        .iter()
                        .find(|i| i.primary)
                        .map(|i| i.name.clone())
                        .unwrap_or_else(|| format!("{}_pkey", old.path.name))
                )
            )),
        }
    }

    // columns: match by name; renames are detected when caller keeps
    // `extra` column ordering — the designer passes renames explicitly via
    // `alter_table_with_renames`.
    out.extend(column_changes(d, &t, old, new, &[]));

    if old_pk != new_pk && !new_pk.is_empty() {
        out.push(format!("ALTER TABLE {} ADD PRIMARY KEY ({})", t, col_list(d, &new_pk)));
    }
    for idx in new.indexes.iter().filter(|i| !i.primary) {
        if !old.indexes.iter().any(|o| o == idx) {
            out.push(index_sql(d, new, idx));
        }
    }
    for fk in &new.foreign_keys {
        if !old.foreign_keys.iter().any(|o| o == fk) {
            out.push(format!("ALTER TABLE {} ADD {}", t, fk_sql(d, fk)));
        }
    }
    for ck in &old.checks {
        if !new.checks.contains(ck) && !ck.name.is_empty() {
            match d {
                Dialect::MySql => out.push(format!("ALTER TABLE {} DROP CHECK {}", t, d.quote_ident(&ck.name))),
                _ => out.push(format!("ALTER TABLE {} DROP CONSTRAINT {}", t, d.quote_ident(&ck.name))),
            }
        }
    }
    for ck in &new.checks {
        if !old.checks.contains(ck) {
            if ck.name.is_empty() {
                out.push(format!("ALTER TABLE {} ADD CHECK ({})", t, ck.expression));
            } else {
                out.push(format!("ALTER TABLE {} ADD CONSTRAINT {} CHECK ({})", t, d.quote_ident(&ck.name), ck.expression));
            }
        }
    }
    // table options
    if d == Dialect::MySql {
        let mut opts = Vec::new();
        if old.engine != new.engine && !new.engine.is_empty() {
            opts.push(format!("ENGINE={}", new.engine));
        }
        if old.comment != new.comment {
            opts.push(format!("COMMENT={}", d.string_literal(&new.comment)));
        }
        if old.charset != new.charset && !new.charset.is_empty() {
            opts.push(format!("DEFAULT CHARSET={}", new.charset));
        }
        if old.collation != new.collation && !new.collation.is_empty() {
            opts.push(format!("COLLATE={}", new.collation));
        }
        if old.auto_increment != new.auto_increment {
            if let Some(ai) = new.auto_increment {
                opts.push(format!("AUTO_INCREMENT={}", ai));
            }
        }
        if !opts.is_empty() {
            out.push(format!("ALTER TABLE {} {}", t, opts.join(" ")));
        }
    } else if old.comment != new.comment {
        out.push(format!("COMMENT ON TABLE {} IS {}", t, d.string_literal(&new.comment)));
    }
    // triggers
    for tr in &old.triggers {
        if !new.triggers.contains(tr) {
            out.push(drop_trigger(d, &old.path, &tr.name));
        }
    }
    for tr in &new.triggers {
        if !old.triggers.contains(tr) {
            out.push(create_trigger(d, &new.path, tr));
        }
    }
    out
}

/// Same as [`alter_table`] but with explicit column renames `(old, new)`.
pub fn alter_table_with_renames(d: Dialect, old: &TableDef, new: &TableDef, renames: &[(String, String)]) -> Vec<String> {
    if renames.is_empty() || d == Dialect::Sqlite {
        if d == Dialect::Sqlite {
            return sqlite_rebuild_with_renames(old, new, renames);
        }
        return alter_table(d, old, new);
    }
    // Apply renames to a copy of `old` so the regular diff only sees real changes.
    let t = d.qualify(&old.path);
    let mut pre = Vec::new();
    let mut renamed_old = old.clone();
    for (from, to) in renames {
        if let Some(c) = renamed_old.columns.iter_mut().find(|c| &c.name == from) {
            match d {
                Dialect::MySql => {
                    let newc = new.column(to).cloned().unwrap_or_else(|| {
                        let mut c2 = c.clone();
                        c2.name = to.clone();
                        c2
                    });
                    pre.push(format!("ALTER TABLE {} CHANGE COLUMN {} {}", t, d.quote_ident(from), column_sql(d, &newc, false)));
                    *c = newc;
                }
                _ => {
                    pre.push(format!("ALTER TABLE {} RENAME COLUMN {} TO {}", t, d.quote_ident(from), d.quote_ident(to)));
                    c.name = to.clone();
                }
            }
        }
        for idx in renamed_old.indexes.iter_mut() {
            for col in idx.columns.iter_mut() {
                if col == from {
                    *col = to.clone();
                }
            }
        }
        for fk in renamed_old.foreign_keys.iter_mut() {
            for col in fk.columns.iter_mut() {
                if col == from {
                    *col = to.clone();
                }
            }
        }
    }
    pre.extend(alter_table(d, &renamed_old, new));
    pre
}

fn column_changes(d: Dialect, t: &str, old: &TableDef, new: &TableDef, _renames: &[(String, String)]) -> Vec<String> {
    let mut out = Vec::new();
    for oc in &old.columns {
        if new.column(&oc.name).is_none() {
            out.push(format!("ALTER TABLE {} DROP COLUMN {}", t, d.quote_ident(&oc.name)));
        }
    }
    for (pos, nc) in new.columns.iter().enumerate() {
        let mut ncp = nc.clone();
        ncp.primary_key = false;
        match old.column(&nc.name) {
            None => {
                let mut s = format!("ALTER TABLE {} ADD COLUMN {}", t, column_sql(d, &ncp, false));
                if d == Dialect::MySql {
                    if pos == 0 {
                        s.push_str(" FIRST");
                    } else {
                        s.push_str(&format!(" AFTER {}", d.quote_ident(&new.columns[pos - 1].name)));
                    }
                }
                out.push(s);
                if d == Dialect::Postgres && !nc.comment.is_empty() {
                    out.push(format!("COMMENT ON COLUMN {}.{} IS {}", t, d.quote_ident(&nc.name), d.string_literal(&nc.comment)));
                }
            }
            Some(oc) => {
                let mut ocp = oc.clone();
                ocp.primary_key = false;
                let old_pos = old.columns.iter().position(|c| c.name == nc.name);
                let moved = d == Dialect::MySql && {
                    // relative order change among surviving columns
                    let prev_new = if pos == 0 { None } else { Some(&new.columns[pos - 1].name) };
                    let prev_old = old_pos.and_then(|p| if p == 0 { None } else { Some(&old.columns[p - 1].name) });
                    prev_new != prev_old
                };
                if ocp == ncp && !moved {
                    continue;
                }
                match d {
                    Dialect::MySql => {
                        let mut s = format!("ALTER TABLE {} MODIFY COLUMN {}", t, column_sql(d, &ncp, false));
                        if moved {
                            if pos == 0 {
                                s.push_str(" FIRST");
                            } else {
                                s.push_str(&format!(" AFTER {}", d.quote_ident(&new.columns[pos - 1].name)));
                            }
                        }
                        out.push(s);
                    }
                    _ => {
                        let col = d.quote_ident(&nc.name);
                        if !oc.data_type.eq_ignore_ascii_case(&nc.data_type) {
                            out.push(format!(
                                "ALTER TABLE {} ALTER COLUMN {} TYPE {} USING {}::{}",
                                t, col, nc.data_type, col, nc.data_type
                            ));
                        }
                        if oc.nullable != nc.nullable {
                            out.push(format!(
                                "ALTER TABLE {} ALTER COLUMN {} {} NOT NULL",
                                t,
                                col,
                                if nc.nullable { "DROP" } else { "SET" }
                            ));
                        }
                        if oc.default != nc.default {
                            match &nc.default {
                                Some(v) if !v.is_empty() => {
                                    out.push(format!("ALTER TABLE {} ALTER COLUMN {} SET DEFAULT {}", t, col, v))
                                }
                                _ => out.push(format!("ALTER TABLE {} ALTER COLUMN {} DROP DEFAULT", t, col)),
                            }
                        }
                        if oc.comment != nc.comment {
                            out.push(format!("COMMENT ON COLUMN {}.{} IS {}", t, col, d.string_literal(&nc.comment)));
                        }
                        if oc.auto_increment != nc.auto_increment {
                            if nc.auto_increment {
                                out.push(format!("ALTER TABLE {} ALTER COLUMN {} ADD GENERATED BY DEFAULT AS IDENTITY", t, col));
                            } else {
                                out.push(format!("ALTER TABLE {} ALTER COLUMN {} DROP IDENTITY IF EXISTS", t, col));
                            }
                        }
                    }
                }
            }
        }
    }
    out
}

fn sqlite_rebuild(old: &TableDef, new: &TableDef) -> Vec<String> {
    sqlite_rebuild_with_renames(old, new, &[])
}

/// SQLite cannot alter most column properties, so the table is rebuilt:
/// create a temp table with the new layout, copy shared columns, swap.
fn sqlite_rebuild_with_renames(old: &TableDef, new: &TableDef, renames: &[(String, String)]) -> Vec<String> {
    let d = Dialect::Sqlite;
    if old == new {
        return vec![];
    }
    // Simple cases that ALTER TABLE handles natively.
    let only_added = old.columns.len() < new.columns.len()
        && new.columns[..old.columns.len()] == old.columns[..]
        && old.indexes == new.indexes
        && old.foreign_keys == new.foreign_keys
        && old.path.name == new.path.name
        && renames.is_empty()
        && old.triggers == new.triggers
        && new.columns[old.columns.len()..].iter().all(|c| !c.primary_key);
    if only_added {
        return new.columns[old.columns.len()..]
            .iter()
            .map(|c| format!("ALTER TABLE {} ADD COLUMN {}", d.qualify(&old.path), column_sql(d, c, false)))
            .collect();
    }
    let mut out = vec!["PRAGMA foreign_keys = OFF".to_string(), "BEGIN".to_string()];
    let tmp_name = format!("_navdb_tmp_{}", new.path.name);
    let mut tmp = new.clone();
    tmp.path.name = tmp_name.clone();
    tmp.triggers.clear();
    // indexes are recreated after rename (names must be unique)
    let indexes = tmp.indexes.clone();
    tmp.indexes.retain(|i| i.primary);
    out.extend(create_table(d, &tmp));
    let mut src_cols = Vec::new();
    let mut dst_cols = Vec::new();
    for nc in &new.columns {
        let src = renames
            .iter()
            .find(|(_, to)| to == &nc.name)
            .map(|(from, _)| from.clone())
            .unwrap_or_else(|| nc.name.clone());
        if old.column(&src).is_some() {
            src_cols.push(d.quote_ident(&src));
            dst_cols.push(d.quote_ident(&nc.name));
        }
    }
    if !src_cols.is_empty() {
        out.push(format!(
            "INSERT INTO {} ({}) SELECT {} FROM {}",
            d.qualify(&tmp.path),
            dst_cols.join(", "),
            src_cols.join(", "),
            d.qualify(&old.path)
        ));
    }
    out.push(format!("DROP TABLE {}", d.qualify(&old.path)));
    out.push(format!("ALTER TABLE {} RENAME TO {}", d.qualify(&tmp.path), d.quote_ident(&new.path.name)));
    let final_def = TableDef { indexes, ..new.clone() };
    for idx in final_def.indexes.iter().filter(|i| !i.primary) {
        out.push(index_sql(d, &final_def, idx));
    }
    for tr in &new.triggers {
        out.push(create_trigger(d, &new.path, tr));
    }
    out.push("COMMIT".to_string());
    out.push("PRAGMA foreign_keys = ON".to_string());
    out
}

pub fn drop_object(d: Dialect, kind: ObjectKind, p: &ObjPath, args: Option<&str>) -> String {
    let name = match (kind, d) {
        (ObjectKind::Function | ObjectKind::Procedure, Dialect::Postgres) => {
            format!("{}({})", d.qualify(p), args.unwrap_or(""))
        }
        _ => d.qualify(p),
    };
    match kind {
        ObjectKind::Trigger if d == Dialect::Postgres => {
            // PG trigger needs the table: args holds table name
            format!("DROP TRIGGER {} ON {}", d.quote_ident(&p.name), args.map(|a| a.to_string()).unwrap_or_default())
        }
        ObjectKind::Index if d == Dialect::MySql => {
            format!("DROP INDEX {} ON {}", d.quote_ident(&p.name), args.unwrap_or(""))
        }
        _ => format!("DROP {} {}", kind.sql_keyword(), name),
    }
}

pub fn drop_trigger(d: Dialect, table: &ObjPath, name: &str) -> String {
    match d {
        Dialect::Postgres => format!("DROP TRIGGER {} ON {}", d.quote_ident(name), d.qualify(table)),
        Dialect::MySql => format!("DROP TRIGGER {}", d.qualify(&ObjPath::new(table.db.clone(), None, name))),
        _ => format!("DROP TRIGGER {}", d.quote_ident(name)),
    }
}

pub fn rename_object(d: Dialect, kind: ObjectKind, p: &ObjPath, new_name: &str) -> String {
    let np = ObjPath::new(p.db.clone(), p.schema.clone(), new_name);
    match (kind, d) {
        (ObjectKind::Table, Dialect::MySql) => format!("RENAME TABLE {} TO {}", d.qualify(p), d.qualify(&np)),
        (ObjectKind::View, Dialect::MySql) => format!("RENAME TABLE {} TO {}", d.qualify(p), d.qualify(&np)),
        (ObjectKind::View, Dialect::Postgres) => format!("ALTER VIEW {} RENAME TO {}", d.qualify(p), d.quote_ident(new_name)),
        (ObjectKind::Sequence, Dialect::Postgres) => {
            format!("ALTER SEQUENCE {} RENAME TO {}", d.qualify(p), d.quote_ident(new_name))
        }
        _ => format!("ALTER TABLE {} RENAME TO {}", d.qualify(p), d.quote_ident(new_name)),
    }
}

pub fn truncate_table(d: Dialect, p: &ObjPath) -> String {
    match d {
        Dialect::Sqlite => format!("DELETE FROM {}", d.qualify(p)),
        _ => format!("TRUNCATE TABLE {}", d.qualify(p)),
    }
}

pub fn empty_table(d: Dialect, p: &ObjPath) -> String {
    format!("DELETE FROM {}", d.qualify(p))
}

pub fn create_database(d: Dialect, name: &str, charset: &str, collation: &str) -> String {
    match d {
        Dialect::MySql => {
            let mut s = format!("CREATE DATABASE {}", d.quote_ident(name));
            if !charset.is_empty() {
                s.push_str(&format!(" CHARACTER SET {}", charset));
            }
            if !collation.is_empty() {
                s.push_str(&format!(" COLLATE {}", collation));
            }
            s
        }
        Dialect::Postgres => {
            let mut s = format!("CREATE DATABASE {}", d.quote_ident(name));
            if !charset.is_empty() {
                s.push_str(&format!(" ENCODING {}", d.string_literal(charset)));
            }
            s
        }
        Dialect::Sqlite => format!("ATTACH DATABASE {} AS {}", d.string_literal(charset), d.quote_ident(name)),
        _ => format!("CREATE DATABASE {}", d.quote_ident(name)),
    }
}

pub fn drop_database(d: Dialect, name: &str) -> String {
    match d {
        Dialect::Sqlite => format!("DETACH DATABASE {}", d.quote_ident(name)),
        _ => format!("DROP DATABASE {}", d.quote_ident(name)),
    }
}

pub fn create_schema(d: Dialect, name: &str) -> String {
    format!("CREATE SCHEMA {}", d.quote_ident(name))
}

pub fn create_view(d: Dialect, p: &ObjPath, select: &str, or_replace: bool) -> String {
    let body = select.trim().trim_end_matches(';');
    match d {
        Dialect::Sqlite => format!("CREATE VIEW {} AS\n{}", d.qualify(p), body),
        _ => format!(
            "CREATE {}VIEW {} AS\n{}",
            if or_replace { "OR REPLACE " } else { "" },
            d.qualify(p),
            body
        ),
    }
}

/// Duplicate a table's structure (and optionally data).
pub fn duplicate_table(d: Dialect, src: &TableDef, new_name: &str, with_data: bool) -> Vec<String> {
    let mut def = src.clone();
    def.path.name = new_name.to_string();
    for idx in def.indexes.iter_mut() {
        if !idx.primary {
            idx.name = format!("{}_{}", new_name, idx.name);
        }
    }
    for fk in def.foreign_keys.iter_mut() {
        if !fk.name.is_empty() {
            fk.name = format!("{}_{}", new_name, fk.name);
        }
    }
    def.triggers.clear();
    let mut out = create_table(d, &def);
    if with_data {
        out.push(format!("INSERT INTO {} SELECT * FROM {}", d.qualify(&def.path), d.qualify(&src.path)));
    }
    out
}

pub fn script(stmts: &[String]) -> String {
    stmts.iter().map(|s| format!("{};", s.trim_end_matches(';'))).collect::<Vec<_>>().join("\n\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn users(d: Dialect) -> TableDef {
        TableDef {
            path: ObjPath::new("app", None, "users"),
            columns: vec![
                ColumnDef { auto_increment: true, primary_key: true, nullable: false, ..ColumnDef::new("id", if d == Dialect::Sqlite { "INTEGER" } else { "int" }) },
                ColumnDef { nullable: false, ..ColumnDef::new("email", "varchar(255)") },
            ],
            indexes: vec![IndexDef { name: "ux_email".into(), columns: vec!["email".into()], unique: true, ..Default::default() }],
            ..Default::default()
        }
    }

    #[test]
    fn create_mysql() {
        let s = script(&create_table(Dialect::MySql, &users(Dialect::MySql)));
        assert!(s.contains("CREATE TABLE `app`.`users`"));
        assert!(s.contains("`id` int NOT NULL AUTO_INCREMENT"));
        assert!(s.contains("PRIMARY KEY (`id`)"));
        assert!(s.contains("UNIQUE KEY `ux_email` (`email`)"));
    }

    #[test]
    fn create_sqlite_inline_pk() {
        let s = script(&create_table(Dialect::Sqlite, &ObjPathFix::fix(users(Dialect::Sqlite))));
        assert!(s.contains("\"id\" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT"), "{}", s);
        assert!(s.contains("CREATE UNIQUE INDEX \"ux_email\" ON \"users\""), "{}", s);
    }

    struct ObjPathFix;
    impl ObjPathFix {
        fn fix(mut t: TableDef) -> TableDef {
            t.path.db = "main".into();
            t
        }
    }

    #[test]
    fn alter_mysql_add_drop() {
        let old = users(Dialect::MySql);
        let mut new = old.clone();
        new.columns.push(ColumnDef::new("name", "varchar(50)"));
        new.indexes.clear();
        let s = alter_table(Dialect::MySql, &old, &new);
        assert!(s.iter().any(|x| x.contains("DROP INDEX `ux_email`")));
        assert!(s.iter().any(|x| x.contains("ADD COLUMN `name` varchar(50) AFTER `email`")), "{:?}", s);
    }

    #[test]
    fn alter_pg_type_and_null() {
        let mut old = users(Dialect::Postgres);
        old.path.schema = Some("public".into());
        let mut new = old.clone();
        new.columns[1].data_type = "text".into();
        new.columns[1].nullable = true;
        let s = alter_table(Dialect::Postgres, &old, &new);
        assert!(s.iter().any(|x| x.contains("ALTER COLUMN \"email\" TYPE text")));
        assert!(s.iter().any(|x| x.contains("ALTER COLUMN \"email\" DROP NOT NULL")));
    }

    #[test]
    fn rename_column_mysql() {
        let old = users(Dialect::MySql);
        let mut new = old.clone();
        new.columns[1].name = "mail".into();
        new.indexes[0].columns = vec!["mail".into()];
        let s = alter_table_with_renames(Dialect::MySql, &old, &new, &[("email".into(), "mail".into())]);
        assert!(s[0].contains("CHANGE COLUMN `email` `mail`"), "{:?}", s);
        assert!(!s.iter().any(|x| x.contains("DROP COLUMN")), "{:?}", s);
    }

    #[test]
    fn sqlite_rebuild_copies() {
        let mut old = users(Dialect::Sqlite);
        old.path.db = "main".into();
        let mut new = old.clone();
        new.columns[1].data_type = "TEXT".into();
        let s = alter_table(Dialect::Sqlite, &old, &new);
        assert!(s.iter().any(|x| x.starts_with("INSERT INTO \"_navdb_tmp_users\"")), "{:?}", s);
        assert!(s.iter().any(|x| x.contains("RENAME TO \"users\"")));
    }
}
